export const getOrigins = (): string[] => {
  const origins = new Set(roasts.map((r) => r.origin));
  return Array.from(origins).sort();
};

export const getProcesses = (): string[] => {
  const processes = new Set(roasts.map((r) => r.process));
  return Array.from(processes).sort();
};

